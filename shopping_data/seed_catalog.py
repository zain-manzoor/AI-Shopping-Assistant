DEMO_CUSTOMERS = (
    ("demo-customer-1", "Demo Customer 1"),
    ("demo-customer-2", "Demo Customer 2"),
    ("demo-customer-3", "Demo Customer 3"),
)


def seed_catalog(connection: sqlite3.Connection) -> None:
    """Insert or refresh the fixed fictional catalog without changing carts."""
    with write_transaction(connection):
        connection.executemany(
            "INSERT INTO categories(category_id, name) VALUES (?, ?) "
            "ON CONFLICT(category_id) DO UPDATE SET name = excluded.name",
            CATEGORIES,
        )
        connection.executemany(
            "INSERT INTO customers(customer_id, display_name) VALUES (?, ?) "
            "ON CONFLICT(customer_id) DO UPDATE SET display_name = excluded.display_name",
            DEMO_CUSTOMERS,
        )
        for item in PRODUCTS:
            product_id, category_id, name, price, stock, *facts = item
            fields = {
                "brand": None,
                "model": None,
                "product_type": None,
                "key_specs": None,
                "size": None,
                "color": None,
                "material": None,
                "fit": None,
                "author": None,
                "genre": None,
                "format": None,
                "home_type": None,
                "home_material": None,
                "dimensions": None,
            }
            category_fields = {
                "electronics": ("brand", "model", "product_type", "key_specs"),
                "clothing": ("size", "color", "material", "fit"),
                "books": ("author", "genre", "format"),
                "home-accessories": ("home_type", "home_material", "dimensions"),
            }[category_id]
            fields.update(zip(category_fields, facts, strict=True))
            connection.execute(
                """INSERT INTO products (
                    product_id, category_id, name, price_paisa, stock_on_hand,
                    brand, model, product_type, key_specs, size, color, material, fit,
                    author, genre, format, home_type, home_material, dimensions
                ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
                ON CONFLICT(product_id) DO UPDATE SET
                    category_id=excluded.category_id, name=excluded.name,
                    price_paisa=excluded.price_paisa, stock_on_hand=excluded.stock_on_hand,
                    brand=excluded.brand, model=excluded.model, product_type=excluded.product_type,
                    key_specs=excluded.key_specs, size=excluded.size, color=excluded.color,
                    material=excluded.material, fit=excluded.fit, author=excluded.author,
                    genre=excluded.genre, format=excluded.format, home_type=excluded.home_type,
                    home_material=excluded.home_material, dimensions=excluded.dimensions""",
                (product_id, category_id, name, price * 100, stock, *fields.values()),
            )
